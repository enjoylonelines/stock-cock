assert.equal(detail.memo,"정정 입고 8개");assert.equal(detail.latest_memo,"재고 변경 없는 메모 정정");
assert.equal((await http("/api/transactions/"+replacement,"PATCH",{revision:0})).status,405);
assert.equal((await http("/api/transactions/"+replacement,"DELETE",{revision:0})).status,405);
console.log("PASS memo is append-only and legacy overwrite/delete endpoints are blocked");
