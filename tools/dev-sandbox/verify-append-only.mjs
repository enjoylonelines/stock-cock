assert.equal((await http("/api/adjustments","POST",{warehouse_id:w2,items:[{option_id:op,quantity:1}]})).status,200);
assert.equal(await stock(),6);
await ok(client.from("effective_transactions").select("id,type,transaction_items!inner(quantity,product_options!inner(products!inner(product_type)))").eq("id",replacement));
assert.ok((await client.from("inventory").update({quantity:999}).eq("product_option_id",op)).error);
