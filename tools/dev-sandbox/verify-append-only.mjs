import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { randomUUID, randomBytes } from "node:crypto";
import { createClient } from "@supabase/supabase-js";
import { createServerClient } from "@supabase/ssr";
const config=JSON.parse(execFileSync("pnpm",["dlx","supabase","status","--workdir","tools/dev-sandbox","--output","json"],{encoding:"utf8",stdio:["ignore","pipe","ignore"]}));
assert.equal(new URL(config.API_URL).port,"55321");
const admin=createClient(config.API_URL,config.SERVICE_ROLE_KEY);
const cookies=new Map();
const client=createServerClient(config.API_URL,config.ANON_KEY,{cookies:{getAll:()=>[...cookies].map(([name,value])=>({name,value})),setAll:values=>values.forEach(({name,value})=>cookies.set(name,value))}});
const email=process.env.MANAGEMENT_DEV_EMAIL||`append-${randomUUID()}@example.test`;
const password=process.env.MANAGEMENT_DEV_PASSWORD||randomBytes(24).toString("base64url");
const ok=async q=>{const {data,error}=await q;assert.ifError(error);return data;};
const auth=await admin.auth.admin.createUser({email,password,email_confirm:true});
assert.ifError(auth.error);
assert.ifError((await client.auth.signInWithPassword({email,password})).error);
await ok(admin.from("profiles").insert({id:auth.data.user.id,name:"정정 검증 사용자",email}));
const brand=(await ok(admin.from("brands").insert({name:"정정 검증 브랜드"}).select().single())).id;
const category=(await ok(admin.from("categories").insert({name:"정정 검증 분류"}).select().single())).id;
const w=(await ok(admin.from("warehouses").insert({name:"정정 검증 창고"}).select().single())).id;
const w2=(await ok(admin.from("warehouses").insert({name:"정정 검증 보조창고"}).select().single())).id;
const http=async(path,method="GET",body)=>{
 const response=await fetch("http://127.0.0.1:3000"+path,{method,headers:{"Content-Type":"application/json",cookie:[...cookies].map(([n,v])=>n+"="+v).join("; ")},...(body?{body:JSON.stringify(body)}:{})});
 return {status:response.status,data:await response.json()};
};
const product=await http("/api/products/manage","POST",{name:"원본 보존 검증 제품",brand_id:brand,category_id:category,warehouse_id:w,product_type:"company",quantity:0,weight:1000,unit_label:"g",sku:randomUUID()});
assert.equal(product.status,200,JSON.stringify(product.data));
const op=product.data.option.id;
const post=async(type,quantity)=>{const r=await http("/api/transactions","POST",{type,warehouse_id:w,items:[{option_id:op,quantity}],memo:"원본 메모: 입고 10개"});assert.equal(r.status,200,JSON.stringify(r.data));return r.data.transaction_id;};
const source=await post("in",10),out=await post("out",2);
const original=(await http("/api/transactions/"+source)).data.data;
const changes={action:"correct",revision:original.revision,reason:"10개 중 2개는 오입력",request_id:randomUUID(),warehouse_id:w,created_at:original.created_at,supplier_id:null,memo:"정정 입고 8개",items:[{option_id:op,quantity:8}]};
const corrected=await http(`/api/transactions/${source}/corrections`,"POST",changes);
assert.equal(corrected.status,200,JSON.stringify(corrected.data));
const replacement=corrected.data.replacement_id;
const sourceAfter=(await http("/api/transactions/"+source)).data.data;
for(const key of ["created_at","memo","user_id","revision","transaction_items"])assert.deepEqual(sourceAfter[key],original[key]);
assert.equal(sourceAfter.transaction_status,"corrected");
const stock=async()=> (await ok(client.from("inventory").select("quantity").eq("product_option_id",op).eq("warehouse_id",w).single())).quantity;
assert.equal(await stock(),6);
assert.equal((await http(`/api/transactions/${source}/corrections`,"POST",changes)).data.replacement_id,replacement);
assert.equal(await stock(),6);
console.log("PASS HTTP correction preserves original, applies net stock, and retries once");
const race=await Promise.all(["first","second"].map(reason=>http(`/api/transactions/${out}/corrections`,"POST",{action:"cancel",revision:0,reason,request_id:randomUUID()})));
assert.deepEqual(race.map(r=>r.status).sort(),[200,409]);
assert.equal(await stock(),8);
console.log("PASS concurrent cancellation accepts one resolution and restores stock once");
const memo=await http(`/api/transactions/${replacement}/corrections`,"POST",{action:"memo",revision:0,reason:"메모 오타",memo:"재고 변경 없는 메모 정정",request_id:randomUUID()});
assert.equal(memo.status,200,JSON.stringify(memo.data));assert.equal(await stock(),8);
